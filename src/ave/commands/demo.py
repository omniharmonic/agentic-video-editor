"""`ave demo [dir]`: run the whole pipeline on a generated, two-camera, 30-second episode. Needs only ffmpeg.

There is no footage to download and nothing leaves your machine. The "footage" is synthetic (coloured frames plus tones that stand in
for two speakers), generated by `ave.synth`, which is the same generator the test suite uses, so the correct answers are known.

Each step is the REAL command a person or agent would run (`ave ingest`, `ave sync`, ...), called in-process. The one stand-in is the
transcript: tones are not speech, so no ASR could transcribe them. The demo writes the generator's known transcript instead and says so.
"""

from __future__ import annotations

import contextlib
import io
import json
import shutil
import sys
import time
from pathlib import Path

from .. import synth, workspace

DEFAULT_DIR = "ave-demo"


class DemoError(RuntimeError):
    pass


def default_dir(cwd: Path | None = None) -> Path:
    """`./ave-demo`, except inside a git checkout (the README tells you to run the demo from the repo): then ~/ave-demo."""
    here = (cwd or Path.cwd()).resolve()
    return Path.home() / DEFAULT_DIR if workspace.in_git_checkout(here) else here / DEFAULT_DIR


def _continue_notes() -> list[str]:
    """What the demo does NOT set up, so the user hears it now rather than from an error three commands later."""
    from .. import config
    notes = []
    model = config.whisper_model()
    if not (config.fluidaudio_cli() or (config.whisper_cli() and model)):
        notes.append("Real transcripts need an ASR engine: FluidAudio (scripts/setup.sh) or whisper.cpp plus its ~1.6 GB model "
                     "(scripts/fetch-whisper-model.sh). `ave transcribe` and `ave final` (which re-transcribes its render) stop without one.")
    elif config.whisper_cli() and not model:
        notes.append("whisper-cli is installed but its ~1.6 GB model is missing: run scripts/fetch-whisper-model.sh.")
    try:
        import playwright  # noqa: F401
        have_pw = True
    except ImportError:
        have_pw = False
    if not have_pw:
        notes.append("Titles, captions burn-in and `ave sequence preview|build` need Playwright: `uv sync --extra motion`, then "
                     "`playwright install chromium` (about 150 MB).")
    notes.append("The demo stops at the rough cut and its audio is synthetic tones, so `ave final` and the Resolve hand-off are not "
                 "meaningful on it; use real footage for those.")
    return notes


def _say(msg: str = "") -> None:
    print(msg, flush=True)


def _call(argv: list[str]) -> dict | list | str:
    """Run `ave <argv>` in-process; return its JSON stdout (or the raw text). A SystemExit or non-zero code becomes a DemoError."""
    from .. import cli
    buf, err = io.StringIO(), io.StringIO()
    try:
        with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(err):
            rc = cli.main(argv)
    except SystemExit as e:
        rc = e.code if isinstance(e.code, int) else 1
        if rc:
            raise DemoError(f"`ave {' '.join(argv)}` stopped: {e.code if not isinstance(e.code, int) else err.getvalue().strip() or buf.getvalue().strip()}") from e
    if rc:
        raise DemoError(f"`ave {' '.join(argv)}` exited {rc}: {(err.getvalue() or buf.getvalue()).strip()[-400:]}")
    out = buf.getvalue().strip()
    try:
        return json.loads(out)
    except ValueError:
        return out


def _first_line(x) -> str:
    return (x if isinstance(x, str) else json.dumps(x))[:200]


def _check_tools() -> None:
    from .. import config
    missing = [t for t in ("ffmpeg", "ffprobe") if not config.binary(t)]
    if missing:
        raise DemoError(f"{' and '.join(missing)} not found on PATH. The demo needs FFmpeg only.\n"
                        "  macOS:          brew install ffmpeg-full\n  Debian/Ubuntu:  sudo apt-get install ffmpeg\n"
                        "  Windows:        winget install ffmpeg   (or use WSL)\n  then re-run: ave demo")


def _transcript_note() -> str:
    from .. import config
    have = []
    if config.fluidaudio_cli():
        have.append("FluidAudio")
    if config.whisper_cli() and config.whisper_model():
        have.append("whisper.cpp")
    base = "the footage is synthetic tones, not speech, so the generator's known transcript is used instead of ASR"
    if have:
        return f"{base} ({' and '.join(have)} found: on real footage `ave transcribe` would use it)"
    return f"{base} (no ASR engine installed; on real footage `ave transcribe` needs FluidAudio on Apple Silicon or whisper.cpp anywhere)"


def run(root: Path, force: bool = False, keep: bool = True) -> dict:
    t0 = time.time()
    _check_tools()
    root = root.expanduser().resolve()
    if root.exists() and any(root.iterdir()) and not (root / "episode.json").exists():
        raise DemoError(f"{root} exists and is not an ave episode. Pick an empty or new folder: ave demo {root}-demo")
    if force and root.exists() and (root / "episode.json").exists():
        shutil.rmtree(root)
    steps: list[dict] = []
    total = 11

    def step(n: int, title: str, what: str, fn):
        _say(f"[{n}/{total}] {title}")
        _say(f"      ave: {what}")
        t = time.time()
        res = fn()
        note = res if isinstance(res, str) else ""
        _say(f"      -> {note}  ({time.time() - t:.1f}s)")
        steps.append({"step": n, "title": title, "note": note})

    ep_arg = str(root)
    _say(f"Demo episode: {root}\nNo footage needed: two synthetic cameras, 30 s, two speakers.\n")

    def init():
        _call(["init-episode", ep_arg, "--title", "Demo episode"])
        return "created episode.json, raw/, work/, edits/, exports/, PROGRESS.md"

    def footage():
        from ..episode import Episode
        ep = Episode(ep_arg)
        if not (ep.raw / "camA.mp4").exists():
            synth.build_media(ep.raw)
        return f"wrote {', '.join(sorted(p.name for p in ep.raw.iterdir() if not p.name.startswith('.')))} into raw/ (known truth: camB starts 1.000 s after camA)"

    def ingest():
        r = _call(["ingest", ep_arg])
        files = r.get("files", []) if isinstance(r, dict) else []
        return f"probed {len(files)} files: " + ", ".join(f"{f['file']} ({f.get('duration', 0):.0f}s)" for f in files)

    def audio():
        outs = _call(["audio", ep_arg])
        return f"extracted analysis audio for {len(str(outs).splitlines())} files into work/audio/"

    def transcribe():
        from ..episode import Episode, write_json
        ep = Episode(ep_arg)
        write_json(ep.artifact("transcript.json"), synth.transcript("raw/camA.mp4"))
        return "work/transcript.json written; " + _transcript_note()

    def sync():
        r = _call(["sync", ep_arg, "--reference", "raw/camA.mp4", "--points", "3"])
        off = r["files"]["raw/camB.mp4"]["start_offset"]
        ok = abs(off - synth.B_OFFSET) < 0.05
        return f"camB offset found = {off:.3f} s (true value {synth.B_OFFSET:.3f}) {'OK' if ok else 'MISMATCH'}"

    def mapcams():
        from ..episode import Episode, read_json, write_json
        ep = Episode(ep_arg)
        meta = read_json(ep.meta_path)
        meta["cameras"] = {"A": {"file": "raw/camA.mp4", "role": "host"}, "B": {"file": "raw/camB.mp4", "role": "guest"}}
        meta["speakers"] = {"S1": {"name": "Host", "camera": "A"}, "S2": {"name": "Guest", "camera": "B"}}
        meta["audio_source"] = "raw/camA.mp4"
        write_json(ep.meta_path, meta)
        return "episode.json: S1/Host on camera A, S2/Guest on camera B (a human confirms this on real footage)"

    def plan():
        r = _call(["plan-cuts", ep_arg])
        return f"work/cutlist.json: {r['stats']}"

    def assemble():
        r = _call(["assemble", ep_arg, "--canvas", "640x360"])
        return f"{Path(r['saved']).name}: {r['video_segments']} shots, {r['duration']:.1f} s, nothing removed"

    def cleanup():
        r = _call(["cleanup", ep_arg, "--no-pacing"])
        t = r["totals"]
        return (f"{Path(r['saved']).name}: {t['input_duration_s']:.1f} s -> {t['output_duration_s']:.1f} s; {t['cuts']} cuts "
                f"({t['dead_air_shortened']} dead-air gaps shortened, {t['fillers_cut']} filler removed), every cut masked; reasons in work/cleanup.json")

    def render():
        r = _call(["render", ep_arg, "--stage", "rough", "--proxy", "--overwrite"])
        return (f"{Path(r['out']).relative_to(root)}: {r['duration']:.1f} s, {r['lufs']} LUFS, "
                f"{'verified' if r.get('ok') else 'NOT verified'} against the edit")

    pipeline = [
        ("Create the episode project", f"init-episode {ep_arg}", init),
        ("Generate synthetic two-camera footage", "(ave.synth, same generator as the tests)", footage),
        ("Ingest: probe the footage", "ingest", ingest),
        ("Audio: analysis tracks", "audio", audio),
        ("Transcript + speakers (stand-in)", "transcribe", transcribe),
        ("Sync the cameras by audio", "sync --reference raw/camA.mp4 --points 3", sync),
        ("Map cameras to speakers", "edit episode.json", mapcams),
        ("Plan shot / reverse-shot cuts", "plan-cuts", plan),
        ("ASSEMBLY (all angles, nothing removed)", "assemble", assemble),
        ("ROUGH CUT (dead air, filler, false starts)", "cleanup", cleanup),
    ]
    for i, (title, what, fn) in enumerate(pipeline, 1):
        step(i, title, what, fn)
    step(11, "Render a draft (proxy preset) with ffmpeg", "render --stage rough --proxy", render)

    summary = {"ok": True, "episode": str(root), "seconds": round(time.time() - t0, 1), "steps": steps}
    _say(f"\nDone in {summary['seconds']} s. Everything is in {root}:")
    _say("  edits/assembly.v1.json   the assembly      edits/rough.v1.json   the rough cut      exports/*.mp4   the draft video")
    _say("  work/*.json              what each stage found, with reasons")
    _say(f"\nLook around:   ave resume {root}      ave status {root}")
    _say("On a human checkpoint with real footage you would now review the assembly, then the rough cut (ave handoff sends it to Resolve).")
    _say("\nBefore you move to real footage:")
    for n in _continue_notes():
        _say(f"  - {n}")
    _say("Next: docs/getting-started.md walks through a real episode (`ave doctor` shows what is still missing).")
    return summary


def cmd(a) -> int:
    try:
        run(Path(a.dir) if a.dir else default_dir(), force=a.force)
    except DemoError as e:
        print(f"\ndemo stopped: {e}", file=sys.stderr)
        return 1
    except (OSError, KeyError, ValueError) as e:     # a bug or a broken ffmpeg: say where, do not dump a traceback on a newcomer
        print(f"\ndemo stopped unexpectedly ({type(e).__name__}: {e}). Run `ave doctor`; if ffmpeg is fine, please report this.",
              file=sys.stderr)
        return 1
    return 0


def register(sub) -> None:
    s = sub.add_parser("demo", help="run the whole pipeline on generated two-camera footage (needs only ffmpeg; no footage, no network)")
    s.add_argument("dir", nargs="?", default=None,
                   help=f"where to build the demo episode (default ./{DEFAULT_DIR}, or ~/{DEFAULT_DIR} when run inside a git checkout; re-runnable)")
    s.add_argument("--force", action="store_true", help="delete and rebuild an existing demo episode in that folder")
    s.set_defaults(fn=cmd)
