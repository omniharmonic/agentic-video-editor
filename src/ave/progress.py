"""PROGRESS.md: the project's memory that survives a cut-off session.

One Markdown file at the project root, readable by humans and agents. Only two things are machine-owned: the checklist block
between the `ave:checklist` markers (regenerated from disk truth, `state.status`) and the lines the commands append. Everything else
(your own notes, edits to any line, extra sections) is never rewritten: appends INSERT a line at the end of their section, and
the checklist replaces only the text between its markers.

Sections: header, Pipeline checklist, Decisions, Open questions for the human, Field notes, Session log (newest last).
"""

from __future__ import annotations

import re
import time
from pathlib import Path

from . import config
from .episode import PRESETS, Episode

START, END = "<!-- ave:checklist:start -->", "<!-- ave:checklist:end -->"
H_CHECK, H_DEC, H_Q, H_NOTES, H_LOG = ("## Pipeline checklist", "## Decisions", "## Open questions for the human",
                                       "## Field notes", "## Session log")
KINDS = ("note", "decision", "question", "done", "blocker")
_Q = re.compile(r"^(\s*)(\d+)\.\s*\[( |x)\]\s*(.*)$")
_F = re.compile(r"^- (F\d+) \[(proposed|applied[^\]]*)\]")


def path(ep: Episode) -> Path:
    return ep.root / "PROGRESS.md"


def now() -> str:
    return time.strftime("%Y-%m-%d %H:%M")


def _write(p: Path, text: str) -> None:
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(p)  # atomic: a cut-off session never leaves a half-written PROGRESS.md


def repo_cmd() -> str:
    return str(config.REPO_ROOT / ".venv" / "bin" / "ave")


def _template(ep: Episode) -> str:
    title = _title(ep)
    return f"""# {title}: production progress

- **Project:** `{ep.root}`
- **Repo (tools + skills):** `{config.REPO_ROOT}`
- **Started:** {time.strftime("%Y-%m-%d")}
- **How to resume:** start a session in the repo (`cd {config.REPO_ROOT}`) and say `Resume {ep.root}`.
  The agent runs `ave doctor`, `ave resume {ep.root}`, and reads this file. Humans may edit anything outside the marked checklist block.

{H_CHECK}

{START}
{END}

{H_DEC}

<!-- One line per decision, with the reason. `ave log <project> "..." --kind decision` adds one. -->

{H_Q}

<!-- Numbered; `ave log <project> "..." --kind question` adds one, `--resolve N` closes it. Answer here or in chat. -->

{H_NOTES}

<!-- What worked, what surprised us, what to change in skills/tools. `ave learn <project> "insight"` adds one (status proposed). -->

{H_LOG}

<!-- Newest last. Stage completions are logged automatically. -->
"""


def _title(ep: Episode) -> str:
    try:
        from .episode import read_json
        return str(read_json(ep.meta_path).get("title") or ep.root.name)
    except Exception:
        return ep.root.name


def _read(ep: Episode) -> str:
    p = path(ep)
    if not p.exists():
        _write(p, _template(ep))
    return p.read_text(encoding="utf-8")


def _bounds(lines: list[str], heading: str) -> tuple[int, int] | None:
    """(index after the heading, index of the next `## ` heading or EOF) for a section, or None."""
    for i, ln in enumerate(lines):
        if ln.strip() == heading:
            for j in range(i + 1, len(lines)):
                if lines[j].startswith("## "):
                    return i + 1, j
            return i + 1, len(lines)
    return None


def _append(text: str, heading: str, line: str) -> str:
    """Insert `line` after the last non-blank line of the section (creating the section at EOF if a human deleted it)."""
    lines = text.split("\n")
    b = _bounds(lines, heading)
    if b is None:
        if lines and lines[-1] != "":
            lines.append("")
        return "\n".join(lines + ["", heading, "", line, ""]).replace("\n\n\n", "\n\n")
    lo, hi = b
    at = lo
    for k in range(lo, hi):
        if lines[k].strip():
            at = k + 1
    if at == lo:                       # empty section: keep a blank line under the heading
        lines.insert(lo, "")
        at = lo + 1
    lines.insert(at, line)
    if at + 1 < len(lines) and lines[at + 1].startswith("## "):
        lines.insert(at + 1, "")       # blank line before the next heading
    return "\n".join(lines)


# ---- checklist ---------------------------------------------------------------------------------------------------

def checklist_block(ep: Episode) -> str:
    from . import state
    st = state.status(ep)
    out = [START, "_Generated by `ave progress` from the files on disk. Do not edit between the markers; write outside them._", ""]
    for r in st["stages"]:
        box = "x" if r["done"] else ("-" if r["skipped"] else " ")
        extra = []
        if r["optional"]:
            extra.append("optional")
        if r["skipped"]:
            extra.append("skipped (single camera)")
        if r["human_gate"] and r["done"]:
            extra.append("human checkpoint")
        if r["blocked_by"] and not r["done"]:
            extra.append("blocked by " + ", ".join(r["blocked_by"]))
        out.append(f"- [{box}] {r['title']} (`{r['stage']}`)" + (f" - {'; '.join(extra)}" if extra else ""))
    out.append("")
    edits = ", ".join(f"{k} v{v[-1]}" for k, v in st["edits"].items())
    out.append(f"**Edits on disk:** {edits or 'none yet'}")
    out.append("")
    pending = (_meta(ep).get("review") or {}).get("pending")
    if pending:
        out += [f"**Waiting on the human:** {pending}", ""]
    n = st["next"]
    if n:
        gate = " Then STOP and get the human's confirmation." if n["human_gate"] else ""
        out.append(f"**Next:** {n['title']}: `{n['command']}` (skill `{n['skill']}`).{gate}")
    else:
        out.append("**Next:** nothing pending. Ask the human what to do next (selects, shorts, publish).")
    out.append(END)
    return "\n".join(out)


def _meta(ep: Episode) -> dict:
    from .episode import read_json
    try:
        return read_json(ep.meta_path)
    except Exception:
        return {}


def _with_block(text: str, block: str) -> str:
    if START in text and END in text and text.index(START) < text.index(END):
        a, b = text.index(START), text.index(END) + len(END)
        return text[:a] + block + text[b:]
    lines = text.split("\n")                       # a human removed the markers: put a fresh block under its heading
    bd = _bounds(lines, H_CHECK)
    if bd is None:
        return text.rstrip("\n") + f"\n\n{H_CHECK}\n\n{block}\n"
    lines[bd[0]:bd[0]] = ["", block]
    return "\n".join(lines)


def refresh(ep: Episode) -> dict:
    """Regenerate the checklist block. Idempotent: writes only when the block changed. Returns a compact summary."""
    text = _read(ep)
    new = _with_block(text, checklist_block(ep))
    changed = new != text
    if changed:
        _write(path(ep), new)
    return {"changed": changed}


# ---- appends -----------------------------------------------------------------------------------------------------

def _mutate(ep: Episode, fn) -> None:
    p = path(ep)
    text = _read(ep)
    new = fn(text)
    if new != text:
        _write(p, new)


def log_line(ep: Episode, message: str, kind: str = "note", step: str | None = None) -> str:
    tag = f"[{kind}]" + (f" [{step}]" if step else "")
    return f"- {now()} {tag} {message}".rstrip()


def log(ep: Episode, message: str, kind: str = "note", step: str | None = None, resolve: int | None = None) -> dict:
    """Route an entry: decisions/questions go to their section AND the session log; `done` also refreshes the checklist."""
    if kind not in KINDS:
        raise SystemExit(f"--kind must be one of {', '.join(KINDS)}")
    message = " ".join(str(message).split())
    if not message and resolve is None:
        raise SystemExit("give a message to log")
    out: dict = {"ok": True, "kind": kind, "file": str(path(ep))}
    stepn = f" [{step}]" if step else ""
    if resolve is not None:
        text = _read(ep)
        text, found = _resolve_question(text, resolve)
        if not found:
            raise SystemExit(f"no open question {resolve} in PROGRESS.md (see `ave resume {ep.root}`)")
        _write(path(ep), text)
        out.update(resolved=resolve)
        message = message or f"question {resolve} answered"
        kind = "note"
        text_line = f"- {now()} [answered{stepn}] Q{resolve}: {message}"
        _mutate(ep, lambda t: _append(t, H_LOG, text_line))
        return out
    if kind == "decision":
        _mutate(ep, lambda t: _append(t, H_DEC, f"- {now()}{stepn} {message}"))
        out["section"] = "Decisions"
    elif kind == "question":
        n = {}

        def add(t: str) -> str:
            n["id"] = next_question_number(t)
            return _append(t, H_Q, f"{n['id']}. [ ] {message} _(asked {now()}{stepn})_")
        _mutate(ep, add)
        out.update(section="Open questions", question=n["id"])
    _mutate(ep, lambda t: _append(t, H_LOG, log_line(ep, message, kind, step)))
    out.setdefault("section", "Session log")
    if kind == "done":
        out["checklist"] = refresh(ep)
    return out


def next_question_number(text: str) -> int:
    nums = [int(m.group(2)) for ln in text.split("\n") if (m := _Q.match(ln))]
    return max(nums, default=0) + 1


def _resolve_question(text: str, n: int) -> tuple[str, bool]:
    lines = text.split("\n")
    b = _bounds(lines, H_Q)
    if b:
        for k in range(*b):
            m = _Q.match(lines[k])
            if m and int(m.group(2)) == n and m.group(3) == " ":
                lines[k] = f"{m.group(1)}{n}. [x] {m.group(4)} _(answered {now()})_"
                return "\n".join(lines), True
    return text, False


def learn(ep: Episode, insight: str, skill: str | None = None, change: str | None = None) -> dict:
    insight = " ".join(str(insight).split())
    if not insight:
        raise SystemExit("give the insight to record")
    box = {}

    def add(t: str) -> str:
        ids = [int(m.group(1)[1:]) for ln in t.split("\n") if (m := _F.match(ln))]
        box["id"] = f"F{max(ids, default=0) + 1}"
        bits = [f"- {box['id']} [proposed] {now()}: {insight}"]
        if skill:
            bits.append(f"skill: `{skill}`")
        if change:
            bits.append(f"proposed change: {' '.join(change.split())}")
        return _append(t, H_NOTES, " | ".join(bits))
    _mutate(ep, add)
    _mutate(ep, lambda t: _append(t, H_LOG, log_line(ep, f"learned {box['id']}: {insight}", "note")))
    return {"ok": True, "id": box["id"], "status": "proposed", "skill": skill, "change": change, "file": str(path(ep))}


def field_notes(ep: Episode, status: str = "proposed") -> list[str]:
    lines = _read(ep).split("\n")
    b = _bounds(lines, H_NOTES)
    return [lines[k] for k in range(*b) if (m := _F.match(lines[k])) and m.group(2).startswith(status)] if b else []


def apply_note(ep: Episode, note_id: str, commit: str | None = None) -> dict:
    """Promotion bookkeeping: mark a field note `applied` (with the commit that put it into a skill/doc/test)."""
    note_id = note_id.upper() if note_id[:1].lower() == "f" else f"F{note_id}"
    box = {"found": False}

    def mark(t: str) -> str:
        ls = t.split("\n")
        for k, ln in enumerate(ls):
            m = _F.match(ln)
            if m and m.group(1) == note_id:
                box["found"] = True
                ls[k] = ln.replace(f"[{m.group(2)}]", f"[applied{' ' + commit if commit else ''}]", 1)
        return "\n".join(ls)
    _mutate(ep, mark)
    if not box["found"]:
        raise SystemExit(f"no field note {note_id} in PROGRESS.md")
    _mutate(ep, lambda t: _append(t, H_LOG, log_line(ep, f"field note {note_id} applied" + (f" ({commit})" if commit else ""), "note")))
    return {"ok": True, "id": note_id, "status": "applied", "commit": commit}


def auto_log(ep: Episode, message: str, kind: str = "note", step: str | None = None, refresh_checklist: bool = True) -> None:
    """The automatic trail (mark_stage, set_review). Only for projects that HAVE a PROGRESS.md, and it never raises:
    bookkeeping must not break a render."""
    try:
        if not path(ep).exists():
            return
        _mutate(ep, lambda t: _append(t, H_LOG, log_line(ep, message, kind, step)))
        if refresh_checklist:
            refresh(ep)
    except Exception:
        pass


# ---- reading it back ---------------------------------------------------------------------------------------------

def open_questions(ep: Episode) -> list[str]:
    if not path(ep).exists():
        return []
    lines = path(ep).read_text(encoding="utf-8").split("\n")
    b = _bounds(lines, H_Q)
    return [lines[k].strip() for k in range(*b) if (m := _Q.match(lines[k])) and m.group(3) == " "] if b else []


def recent_log(ep: Episode, n: int = 5) -> list[str]:
    if not path(ep).exists():
        return []
    lines = path(ep).read_text(encoding="utf-8").split("\n")
    b = _bounds(lines, H_LOG)
    return [lines[k] for k in range(*b) if lines[k].startswith("- ")][-n:] if b else []


def derived_questions(ep: Episode) -> list[str]:
    """Open questions that follow from artifacts on disk rather than from PROGRESS.md: today, a trim suggestion nobody has approved yet."""
    try:
        from . import trim
        return trim.pending_questions(ep)
    except Exception:
        return []


def resume_extras(ep: Episode) -> list[str]:
    if not path(ep).exists():
        out = ["", f"No PROGRESS.md yet. Run: ave progress {ep.root}  (creates it; then log with `ave log`)."]
        dq = derived_questions(ep)
        return out + (["", "Open questions for the human:"] + [f"  {q}" for q in dq] if dq else [])
    out = ["", f"Project memory: {path(ep)}  (read it; log what you do with `ave log`, insights with `ave learn`)"]
    qs = open_questions(ep) + derived_questions(ep)
    out += ["", "Open questions for the human:" if qs else "Open questions for the human: none"] + [f"  {q}" for q in qs]
    log_ = recent_log(ep)
    if log_:
        out += ["", "Last session-log lines:"] + [f"  {ln}" for ln in log_]
    return out


# ---- adopting a project folder -----------------------------------------------------------------------------------

def _agents_md(ep: Episode) -> str:
    return f"""# Agent instructions for this project folder

This folder is a video-editing project managed by the Agentic Video Editor (`ave`). Its tools, skills and rules live in the repo:

    {config.REPO_ROOT}

**Resume work:** open a session in that repo and say `Resume {ep.root}`. The first steps are always:

1. `{repo_cmd()} doctor`
2. `{repo_cmd()} resume {ep.root}`  (what is done, what is next, open questions, last log lines)
3. Read `PROGRESS.md` in this folder.

Read `{config.REPO_ROOT / 'AGENTS.md'}` for the rules (raw footage is read-only; stop at human checkpoints; never publish without approval)
and `{config.REPO_ROOT / 'skills' / 'ave-session-protocol' / 'SKILL.md'}` for how to log progress and learnings.
Do not put footage, secrets or generated media in the repo; do not move or rename anything in the footage folders.
"""


def _claude_md() -> str:
    return "Read `AGENTS.md` in this folder first (it points to the tools repo and the resume steps), then `PROGRESS.md`.\n"


def adopt(ep: Episode) -> dict:
    """Write PROGRESS.md, AGENTS.md and CLAUDE.md in the project root, ONLY IF MISSING (existing files are never touched).
    Plain files, no symlinks: the project may live on an ExFAT drive."""
    created, kept = [], []
    for name, make in (("PROGRESS.md", None), ("AGENTS.md", lambda: _agents_md(ep)), ("CLAUDE.md", _claude_md)):
        p = ep.root / name
        if p.exists():
            kept.append(name)
            continue
        if make is None:
            _write(p, _template(ep))
        else:
            _write(p, make())
        created.append(name)
    refresh(ep)
    if "PROGRESS.md" in created:
        _mutate(ep, lambda t: _append(t, H_LOG, log_line(ep, f"project adopted by ave (layout: {next((n for n, v in PRESETS.items() if v == ep.layout), 'custom')})", "note")))
    return {"created": created, "kept": kept}


def summary(ep: Episode) -> dict:
    from . import state
    st = state.status(ep)
    n = st["next"]
    return {"progress_file": str(path(ep)),
            "done": [r["stage"] for r in st["stages"] if r["done"]],
            "edits": {k: v[-1] for k, v in st["edits"].items()},
            "next": {"stage": n["stage"], "command": n["command"], "skill": n["skill"], "human_gate": n["human_gate"]} if n else None,
            "open_questions": open_questions(ep), "recent_log": recent_log(ep)}
